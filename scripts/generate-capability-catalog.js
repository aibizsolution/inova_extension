#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const MANIFEST_PATH = path.join("hosting", "extension-v2", "capability-manifest.json");

function buildCapabilityCatalogMarkdown(options = {}) {
  const repoRoot = options.root || root;
  const manifest = readJson(path.join(repoRoot, MANIFEST_PATH));
  const capabilities = Object.entries(manifest.capabilities || {})
    .sort(([left], [right]) => left.localeCompare(right));
  const aliases = Object.entries(manifest.aliases || {})
    .sort(([left], [right]) => left.localeCompare(right));
  const rows = capabilities.map(([capabilityId, capability]) => [
    capabilityId,
    capability.kind,
    capability.service,
    formatCapabilityTarget(capability),
    capability.owner,
    capability.domain,
    capability.authMode,
    capability.auditLevel,
    formatSchemaVersion(capability),
    capability.minExtensionVersion,
    capability.enabled === false ? "no" : "yes",
  ]);
  const aliasRows = aliases.map(([aliasId, alias]) => [
    aliasId,
    alias.replacementId,
    manifest.capabilities?.[alias.replacementId]?.kind || "",
    alias.owner,
    alias.removeAfter,
  ]);

  return [
    "# Remote Capability Catalog",
    "",
    "Generated from `hosting/extension-v2/capability-manifest.json`.",
    "Do not edit this file by hand. Run `node scripts/generate-capability-catalog.js > docs/capability-catalog.md` after manifest changes.",
    "",
    `- manifestVersion: \`${manifest.manifestVersion || ""}\``,
    `- schemaVersion: \`${manifest.schemaVersion || ""}\``,
    `- minExtensionVersion: \`${manifest.minExtensionVersion || ""}\``,
    `- expiresAt: \`${manifest.expiresAt || ""}\``,
    `- capabilities: \`${rows.length}\``,
    `- aliases: \`${aliasRows.length}\``,
    "",
    "## Capabilities",
    "",
    "| capabilityId | kind | service | target | owner | domain | authMode | audit | schema | minExtension | enabled |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ...rows.map((row) => `| ${row.map(escapeCell).join(" | ")} |`),
    "",
    "## Aliases",
    "",
    "| aliasId | replacementId | replacementKind | owner | removeAfter |",
    "| --- | --- | --- | --- | --- |",
    ...(aliasRows.length
      ? aliasRows.map((row) => `| ${row.map(escapeCell).join(" | ")} |`)
      : ["| _none_ |  |  |  |  |"]),
    "",
  ].join("\n");
}

function formatSchemaVersion(capability) {
  return `in:${Number(capability.inputSchemaVersion) || 0}/out:${Number(capability.outputSchemaVersion) || 0}`;
}

function formatCapabilityTarget(capability) {
  if (capability?.endpointKey) {
    return capability.endpointKey;
  }
  if (capability?.pageCapabilityId) {
    return capability.pageCapabilityId;
  }
  if (Array.isArray(capability?.templateKeys)) {
    return capability.templateKeys.join(",");
  }
  if (capability?.artifactId || capability?.workflowId) {
    return [capability.workflowId, capability.artifactId, capability.artifactVersion]
      .filter(Boolean)
      .join("@");
  }
  return "";
}

function escapeCell(value) {
  return String(value ?? "").replaceAll("|", "\\|");
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

if (require.main === module) {
  process.stdout.write(buildCapabilityCatalogMarkdown());
}

module.exports = {
  buildCapabilityCatalogMarkdown,
};
